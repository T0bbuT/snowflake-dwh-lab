/*
================================================================================
DBのログ出力先設定
================================================================================
前提: ensure_event_table.sql でログ保存先を作成済みであること。
初回構築・DB再構築後、またはログ出力先を設定し直す場合に実行する。
対象DB内のプロシージャのログを、同じDBのEvent Tableへ出力する。
アカウント全体の出力先は変更しない。
通常のデータ更新・プロシージャ更新では実行しない。
================================================================================
*/

USE ROLE ACCOUNTADMIN;

ALTER DATABASE <% db %> SET EVENT_TABLE = '<% db %>.STAGING.LOAD_EVENTS';

