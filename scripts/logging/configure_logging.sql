/*
================================================================================
ロードプロシージャのログレベル設定
================================================================================
前提: Bronze / Silverの両ロードプロシージャをSYSADMINで作成済みであること。
初回のプロシージャ作成後、およびプロシージャを再作成した後に実行する。
既存ログを保持したまま、両プロシージャのログレベルをINFOに設定する。
================================================================================
*/

USE ROLE SYSADMIN;

ALTER PROCEDURE <% db %>.BRONZE.LOAD_BRONZE() SET LOG_LEVEL = 'INFO';
ALTER PROCEDURE <% db %>.SILVER.LOAD_SILVER() SET LOG_LEVEL = 'INFO';
